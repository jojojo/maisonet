<?php

use App\Actions\Families\LinkMemberAccount;
use App\Actions\Families\RenewFamilyInvitationCode;
use App\Actions\Families\UpdateFamily;
use App\Actions\Families\UpdateParentAccess;
use App\Actions\Goals\SelectRewardTarget;
use App\Actions\Goals\UpdateGoalSettings;
use App\Actions\Kiosk\CompleteKioskTask;
use App\Actions\Kiosk\EnterKiosk;
use App\Actions\Kiosk\LeaveKiosk;
use App\Actions\Members\CreateMember;
use App\Actions\Members\DeleteMember;
use App\Actions\Members\UpdateMember;
use App\Actions\Rewards\CreateReward;
use App\Actions\Rewards\RequestReward;
use App\Actions\Rewards\ReviewRewardRequest;
use App\Actions\Rewards\UpdateReward;
use App\Actions\Rooms\CreateRoom;
use App\Actions\Rooms\DeleteRoom;
use App\Actions\Rooms\UpdateRoom;
use App\Actions\Tasks\CompleteTask;
use App\Actions\Tasks\CreateTask;
use App\Actions\Tasks\DeleteTask;
use App\Actions\Tasks\ImportTaskTemplates;
use App\Actions\Tasks\ReviewTaskCompletion;
use App\Actions\Tasks\SkipTaskOccurrence;
use App\Actions\Tasks\UndoSkippedOccurrence;
use App\Actions\Tasks\UndoTaskCompletion;
use App\Actions\Tasks\UpdateTask;
use App\Http\Controllers\DashboardController;
use App\Http\Controllers\FamilyController;
use App\Http\Controllers\GoalController;
use App\Http\Controllers\KioskController;
use App\Http\Controllers\MemberController;
use App\Http\Controllers\PlanningController;
use App\Http\Controllers\RewardController;
use App\Http\Controllers\RoomController;
use App\Http\Controllers\TaskController;
use App\Http\Controllers\TaskTemplateController;
use Illuminate\Support\Facades\Route;

Route::redirect('/', '/dashboard')->name('home');
Route::view('mobile', 'mobile')->name('mobile');

Route::middleware(['auth'])->group(function () {
    Route::get('dashboard', DashboardController::class)->name('dashboard');
    Route::get('family', [FamilyController::class, 'index'])->name('family.index');
    Route::patch('family', UpdateFamily::class)->name('family.update');
    Route::post('family/code', RenewFamilyInvitationCode::class)->middleware('throttle:6,1')->name('family.renew-code');
    Route::get('kiosk', [KioskController::class, 'index'])->name('kiosk.index');
    Route::post('kiosk/enter', EnterKiosk::class)->name('kiosk.enter');
    Route::post('kiosk/leave', LeaveKiosk::class)->middleware('throttle:6,1')->name('kiosk.leave');
    Route::post('kiosk/tasks/{task}/complete', CompleteKioskTask::class)->name('kiosk.complete');
    Route::post('kiosk/tasks/{task}/skip', SkipTaskOccurrence::class)->middleware('throttle:6,1')->name('kiosk.skip');
    Route::delete('kiosk/tasks/{task}/skip', UndoSkippedOccurrence::class)->middleware('throttle:6,1')->name('kiosk.undo-skip');
    Route::get('planning', PlanningController::class)->name('planning');
    Route::get('task-templates', [TaskTemplateController::class, 'index'])->name('task-templates.index');
    Route::post('task-templates/import', ImportTaskTemplates::class)->name('task-templates.store');
    Route::get('rewards', [RewardController::class, 'index'])->name('rewards.index');
    Route::post('rewards', CreateReward::class)->name('rewards.store');
    Route::patch('rewards/parents/{user}', UpdateParentAccess::class)->name('rewards.parents.update');
    Route::patch('rewards/{reward}', UpdateReward::class)->name('rewards.update');
    Route::get('goals', [GoalController::class, 'index'])->name('goals.index');
    Route::patch('goals/members/{member}', UpdateGoalSettings::class)->name('goals.settings');
    Route::patch('goals/accounts/{user}', LinkMemberAccount::class)->name('goals.link-account');
    Route::post('goals/target', SelectRewardTarget::class)->name('goals.target');
    Route::post('goals/completions/{completion}/review', ReviewTaskCompletion::class)->name('goals.review-completion');
    Route::post('goals/reward-requests', RequestReward::class)->name('goals.request-reward');
    Route::post('goals/reward-requests/{rewardRequest}/review', ReviewRewardRequest::class)->name('goals.review-request');

    Route::get('rooms', [RoomController::class, 'index'])->name('rooms.index');
    Route::get('rooms/{room}', [RoomController::class, 'show'])->name('rooms.show');
    Route::post('rooms', CreateRoom::class)->name('rooms.store');
    Route::match(['put', 'patch'], 'rooms/{room}', UpdateRoom::class)->name('rooms.update');
    Route::delete('rooms/{room}', DeleteRoom::class)->name('rooms.destroy');
    Route::get('members', [MemberController::class, 'index'])->name('members.index');
    Route::post('members', CreateMember::class)->name('members.store');
    Route::match(['put', 'patch'], 'members/{member}', UpdateMember::class)->name('members.update');
    Route::delete('members/{member}', DeleteMember::class)->name('members.destroy');
    Route::get('tasks', [TaskController::class, 'index'])->name('tasks.index');
    Route::post('tasks', CreateTask::class)->name('tasks.store');
    Route::match(['put', 'patch'], 'tasks/{task}', UpdateTask::class)->name('tasks.update');
    Route::delete('tasks/{task}', DeleteTask::class)->name('tasks.destroy');

    Route::post('tasks/{task}/complete', CompleteTask::class)->name('tasks.complete');
    Route::post('tasks/{task}/skip', SkipTaskOccurrence::class)->name('tasks.skip');
    Route::delete('tasks/{task}/skip', UndoSkippedOccurrence::class)->name('tasks.undo-skip');
    Route::delete('tasks/{task}/complete', UndoTaskCompletion::class)->name('tasks.undo');
});

require __DIR__.'/settings.php';
require __DIR__.'/auth.php';
